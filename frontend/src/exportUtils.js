// Pure helpers to export a synthesis object as Markdown or as a print-ready
// academic-paper HTML document. No React / DOM dependencies here so this module
// can be unit-tested in plain Node.

export function slugify(s) {
  return (
    String(s || "synthesis")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 60) || "synthesis"
  )
}

export function escapeHtml(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
}

// Author list in an academic style: up to 3 names, then "et al.".
export function formatAuthors(paper) {
  const authors = paper && paper.authors ? paper.authors : []
  if (authors.length === 0) return "Unknown authors"
  if (authors.length <= 3) return authors.join(", ")
  return authors.slice(0, 3).join(", ") + " et al."
}

export function paperYear(paper) {
  return paper && paper.published ? paper.published.slice(0, 4) : "n.d."
}

// One reference line as plain text (used for both Markdown and PDF).
export function referenceText(paper) {
  let ref = `${formatAuthors(paper)} (${paperYear(paper)}). ${paper.title}.`
  if (paper.source) ref += ` ${paper.source}.`
  if (paper.citation_count != null) ref += ` ${paper.citation_count} citations.`
  if (paper.url) ref += ` ${paper.url}`
  return ref
}

export function buildMarkdown(synthesis) {
  const papers = synthesis.papers || {}
  const today = new Date().toISOString().slice(0, 10)
  const out = []

  out.push(`# ${synthesis.title}`, "")
  out.push(`*Generated by Academic Paper Assistant — ${today}*`, "")
  out.push("## Abstract", "", synthesis.overview || "", "")

  if (synthesis.themes && synthesis.themes.length) {
    out.push("## Themes", "")
    synthesis.themes.forEach((t, i) => {
      out.push(`### ${i + 1}. ${t.title}`, "", t.summary || "", "")
    })
  }

  if (synthesis.trends && synthesis.trends.length) {
    out.push("## Research Trends", "")
    synthesis.trends.forEach((t) => out.push(`- ${t.trend}`))
    out.push("")
  }

  if (synthesis.open_problems && synthesis.open_problems.length) {
    out.push("## Open Problems", "")
    synthesis.open_problems.forEach((p) => out.push(`- ${p.problem}`))
    out.push("")
  }

  if (synthesis.where_to_start && synthesis.where_to_start.length) {
    out.push("## Where to Start", "")
    synthesis.where_to_start.forEach((w) => {
      const p = papers[w.paper_id]
      const title = p ? p.title : w.paper_id
      out.push(`- **${title}** — ${w.reason}`)
    })
    out.push("")
  }

  // Only cite papers that have a real source link — no incomplete entries.
  const ids = Object.keys(papers).filter((id) => papers[id] && papers[id].url)
  if (ids.length) {
    out.push("## References", "")
    ids.forEach((id, i) => out.push(`${i + 1}. ${referenceText(papers[id])}`))
    out.push("")
  }

  return out.join("\n")
}

// A self-contained, print-optimized HTML document styled like an academic paper.
// Opened in a new tab and sent to the browser's print / "Save as PDF".
export function buildPaperHtml(synthesis) {
  const papers = synthesis.papers || {}
  const esc = escapeHtml
  const today = new Date().toISOString().slice(0, 10)

  const themes = (synthesis.themes || [])
    .map((t, i) => `<h3>${i + 1}. ${esc(t.title)}</h3><p>${esc(t.summary)}</p>`)
    .join("")

  const trends = (synthesis.trends || []).length
    ? `<h2>Research Trends</h2><ul>${synthesis.trends
        .map((t) => `<li>${esc(t.trend)}</li>`)
        .join("")}</ul>`
    : ""

  const openProblems = (synthesis.open_problems || []).length
    ? `<h2>Open Problems</h2><ul>${synthesis.open_problems
        .map((p) => `<li>${esc(p.problem)}</li>`)
        .join("")}</ul>`
    : ""

  const whereToStart = (synthesis.where_to_start || []).length
    ? `<h2>Where to Start</h2><ul>${synthesis.where_to_start
        .map((w) => {
          const p = papers[w.paper_id]
          const title = p ? p.title : w.paper_id
          return `<li><strong>${esc(title)}</strong> — ${esc(w.reason)}</li>`
        })
        .join("")}</ul>`
    : ""

  // Only cite papers that have a real source link — no incomplete entries.
  const ids = Object.keys(papers).filter((id) => papers[id] && papers[id].url)
  const references = ids.length
    ? `<h2>References</h2><ol class="refs">${ids
        .map((id) => `<li>${esc(referenceText(papers[id]))}</li>`)
        .join("")}</ol>`
    : ""

  const css = `
    /* margin:0 removes the browser's own print header/footer (date, page title,
       the about:blank URL, page numbers). Page margins are recreated with body
       padding instead. */
    @page { size: A4; margin: 0; }
    * { box-sizing: border-box; }
    body { font-family: "Times New Roman", Georgia, serif; color:#111; line-height:1.5; font-size:11pt; margin:0; padding:1.8cm 2cm; }
    h1.title { text-align:center; font-size:20pt; margin:0 0 6px; }
    .meta { text-align:center; color:#555; font-style:italic; font-size:10pt; margin-bottom:1.6em; }
    h2 { font-size:13pt; border-bottom:1px solid #ccc; padding-bottom:2px; margin:1.4em 0 .4em; }
    h3 { font-size:11.5pt; margin:.9em 0 .2em; }
    p { text-align:justify; margin:.4em 0; }
    .abstract p { font-size:10.5pt; }
    ul { margin:.3em 0; padding-left:1.3em; }
    li { margin:.25em 0; }
    ol.refs li { font-size:10pt; margin:.35em 0; }
    a { color:#111; text-decoration:none; }
  `

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${esc(synthesis.title)}</title>
<style>${css}</style>
</head>
<body>
  <h1 class="title">${esc(synthesis.title)}</h1>
  <div class="meta">Academic Paper Assistant · ${today}</div>
  <div class="abstract"><h2>Abstract</h2><p>${esc(synthesis.overview)}</p></div>
  ${themes ? `<h2>Themes</h2>${themes}` : ""}
  ${trends}
  ${openProblems}
  ${whereToStart}
  ${references}
  <script>window.addEventListener("load",function(){setTimeout(function(){window.print()},300)})<\/script>
</body>
</html>`
}
